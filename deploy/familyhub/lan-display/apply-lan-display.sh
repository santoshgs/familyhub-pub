#!/usr/bin/env bash
# Install or update the FamilyHub LAN display listener on the Pi. Safe to rerun.
#
#   sudo ./apply-lan-display.sh <reserved-frame-ip> <lan-hostname>
#   e.g. sudo ./apply-lan-display.sh 10.0.0.x frame.example.com
#
# - Certificate for <lan-hostname> from Let's Encrypt via Cloudflare DNS
#   (certbot + python3-certbot-dns-cloudflare). Prompts once for a Cloudflare API
#   token limited to that zone's DNS; stores it root-only on the Pi.
# - Host Caddy serves only the read-only display on the Pi's LAN address.
# - nftables table inet familyhub_lan: HTTPS from the frame, SSH from the home
#   network, Tailscale transport, DHCP/IPv6 control; other new LAN input dropped
#   on Wi-Fi and Ethernet. Docker and Tailscale tables are not touched.
# - Removes the earlier Pi-hosted DNS resolver and Tailscale LAN certificate units.
set -Eeuo pipefail
trap 'printf "\nFailed at line %s. Nothing after that step was applied. Backups: %s\n" "$LINENO" "${BACKUP:-none}" >&2' ERR

[[ ${EUID} -eq 0 ]] || { printf 'Run with sudo.\n' >&2; exit 1; }
FRAME_IP=${1:-}; LAN_HOST=${2:-}
[[ -n ${FRAME_IP} && -n ${LAN_HOST} ]] || { printf 'Usage: sudo %s <reserved-frame-ip> <lan-hostname>\n' "$0" >&2; exit 2; }
[[ ${LAN_HOST} =~ ^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$ ]] || { printf 'Invalid hostname: %s\n' "$LAN_HOST" >&2; exit 2; }

SOURCE_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
for file in Caddyfile.lan caddy-familyhub-lan.conf familyhub-firewall.service familyhub-cert-deploy.sh; do
	[[ -f ${SOURCE_DIR}/${file} ]] || { printf 'Missing deployment file: %s\n' "$file" >&2; exit 1; }
done

WIFI=wlan0
PI_CIDR=$(ip -o -4 addr show dev "$WIFI" scope global | awk 'NR == 1 { print $4 }')
PI_IP=${PI_CIDR%/*}
LAN_V6_CIDR=$(ip -o -6 addr show dev "$WIFI" scope global | awk 'NR == 1 { print $4 }')
[[ -n ${PI_CIDR} ]] || { printf 'No IPv4 address on %s.\n' "$WIFI" >&2; exit 1; }
read -r LAN_V4 LAN_V6 < <(python3 - "$FRAME_IP" "$PI_CIDR" "$LAN_V6_CIDR" <<'PY'
import ipaddress, sys
frame = ipaddress.IPv4Address(sys.argv[1]); pi = ipaddress.IPv4Interface(sys.argv[2])
if frame not in pi.network or frame == pi.ip:
    raise SystemExit("The frame address must be in the Pi's Wi-Fi subnet and differ from the Pi.")
print(pi.network, str(ipaddress.IPv6Interface(sys.argv[3]).network) if sys.argv[3] else "-")
PY
)
[[ -n ${LAN_V4:-} ]] || { printf 'Could not validate the frame address against the Pi subnet.\n' >&2; exit 2; }

STAMP=$(date +%Y%m%d-%H%M%S)
BACKUP=/root/familyhub-lan-backup/${STAMP}
install -d -o root -g root -m 0700 "$BACKUP"
nft -a list ruleset > "$BACKUP/ruleset.nft"
for f in /etc/caddy/Caddyfile /etc/family-hub-lan /etc/systemd/system/familyhub-*.service /etc/systemd/system/familyhub-*.timer /etc/systemd/system/caddy.service.d; do
	[[ -e $f ]] && cp -a "$f" "$BACKUP/" || true
done
printf '== Backup of current state: %s\n' "$BACKUP"

printf '== Packages\n'
if ! command -v caddy >/dev/null; then printf 'Caddy is not installed; install it first (see README).\n' >&2; exit 1; fi
if ! dpkg -s certbot python3-certbot-dns-cloudflare >/dev/null 2>&1; then
	apt-get update -q && apt-get install -y -q certbot python3-certbot-dns-cloudflare
fi

install -d -o root -g caddy -m 0750 /etc/family-hub-lan
CF=/etc/family-hub-lan/cloudflare.ini
if [[ ! -s ${CF} ]]; then
	printf '\nCloudflare API token (Zone DNS Edit for this domain only). Input is hidden: '
	read -rs CF_TOKEN; printf '\n'
	[[ -n ${CF_TOKEN} ]] || { printf 'No token entered.\n' >&2; exit 1; }
	( umask 077; printf 'dns_cloudflare_api_token = %s\n' "$CF_TOKEN" > "$CF" )
	unset CF_TOKEN
fi
chown root:root "$CF"; chmod 0600 "$CF"

printf 'FAMILYHUB_LAN_IP=%s\nFAMILYHUB_LAN_HOST=%s\n' "$PI_IP" "$LAN_HOST" > /etc/family-hub-lan/listener.env
chown root:caddy /etc/family-hub-lan/listener.env; chmod 0640 /etc/family-hub-lan/listener.env
install -o root -g root -m 0755 "${SOURCE_DIR}/familyhub-cert-deploy.sh" /etc/family-hub-lan/cert-deploy.sh

printf '== Certificate for %s\n' "$LAN_HOST"
certbot certonly --non-interactive --agree-tos --register-unsafely-without-email --keep-until-expiring \
	--dns-cloudflare --dns-cloudflare-credentials "$CF" --dns-cloudflare-propagation-seconds 30 \
	--deploy-hook /etc/family-hub-lan/cert-deploy.sh -d "$LAN_HOST"
RENEWED_LINEAGE=/etc/letsencrypt/live/${LAN_HOST} FAMILYHUB_LAN_HOST=$LAN_HOST /etc/family-hub-lan/cert-deploy.sh
openssl x509 -in /etc/family-hub-lan/lan-cert.pem -noout -subject -enddate
systemctl enable --now certbot.timer >/dev/null 2>&1 || true

printf '== Firewall rules\n'
SSH_V6=""; TS_V6=""
if [[ ${LAN_V6} != "-" ]]; then
	SSH_V6="iifname \$LAN_IFS ip6 saddr ${LAN_V6} tcp dport 22 accept"
	TS_V6="iifname \$LAN_IFS ip6 saddr ${LAN_V6} udp dport 41641 accept"
fi
RULES=/etc/family-hub-lan/firewall.nft
cat > "${RULES}.new" <<NFT
# Generated by apply-lan-display.sh on ${STAMP}. Replaces only this table.
define LAN_IFS = { "wlan0", "eth0" }
table inet familyhub_lan
delete table inet familyhub_lan
table inet familyhub_lan {
	chain input {
		type filter hook input priority -10; policy accept;
		ct state established,related accept
		iifname "lo" accept
		iifname "tailscale0" accept
		iifname \$LAN_IFS ip saddr ${FRAME_IP} tcp dport 443 accept
		iifname \$LAN_IFS ip saddr ${LAN_V4} tcp dport 22 accept
		${SSH_V6}
		iifname \$LAN_IFS ip6 saddr fe80::/10 tcp dport 22 accept
		iifname \$LAN_IFS ip saddr ${LAN_V4} icmp type echo-request accept
		iifname \$LAN_IFS ip saddr ${LAN_V4} udp dport 41641 accept
		${TS_V6}
		iifname \$LAN_IFS udp sport 67 udp dport 68 accept
		iifname \$LAN_IFS ip6 saddr fe80::/10 udp sport 547 udp dport 546 accept
		iifname \$LAN_IFS ip6 saddr fe80::/10 icmpv6 type { nd-neighbor-solicit, nd-neighbor-advert, nd-router-solicit, nd-router-advert } accept
		iifname \$LAN_IFS icmpv6 type { destination-unreachable, packet-too-big, time-exceeded, parameter-problem, echo-request } accept
		iifname \$LAN_IFS drop
	}
}
NFT
nft -c -f "${RULES}.new"
mv "${RULES}.new" "$RULES"; chown root:root "$RULES"; chmod 0600 "$RULES"

printf '== Caddy configuration\n'
export FAMILYHUB_LAN_IP=$PI_IP FAMILYHUB_LAN_HOST=$LAN_HOST
caddy validate --config "${SOURCE_DIR}/Caddyfile.lan" --adapter caddyfile >/dev/null
install -o root -g caddy -m 0640 "${SOURCE_DIR}/Caddyfile.lan" /etc/caddy/Caddyfile
install -D -o root -g root -m 0644 "${SOURCE_DIR}/caddy-familyhub-lan.conf" /etc/systemd/system/caddy.service.d/familyhub-lan.conf
install -o root -g root -m 0644 "${SOURCE_DIR}/familyhub-firewall.service" /etc/systemd/system/familyhub-firewall.service

printf '== Retire the Pi DNS resolver and Tailscale LAN certificate units\n'
for unit in familyhub-dns.service familyhub-cert.timer familyhub-cert.service; do
	systemctl disable --now "$unit" >/dev/null 2>&1 || true
	rm -f "/etc/systemd/system/${unit}"
done
rm -f /etc/family-hub-lan/cert.pem /etc/family-hub-lan/key.pem

systemctl daemon-reload
systemctl enable familyhub-firewall.service >/dev/null
nft -f "$RULES"   # atomic replace of the table; no window with the LAN open
systemctl restart familyhub-firewall.service
systemctl enable caddy >/dev/null
systemctl restart caddy

printf '== Docker version\n'
DOCKER_VERSION=$(docker version --format '{{.Server.Version}}' 2>/dev/null || echo unknown)
printf 'Docker Engine %s\n' "$DOCKER_VERSION"
if [[ ${DOCKER_VERSION%%.*} =~ ^[0-9]+$ ]] && (( ${DOCKER_VERSION%%.*} < 28 )); then
	printf 'WARNING: Docker older than 28 can expose 127.0.0.1-published ports to devices on the same network. Upgrade Docker.\n'
fi

printf '== Route checks (from the Pi itself)\n'
check() {
	local args=(-s -o /dev/null -w '%{http_code} %{redirect_url}\n' -X "$1" --resolve "${LAN_HOST}:443:${PI_IP}")
	[[ -n ${3:-} ]] && args+=(-H 'Content-Type: application/json' -d "$3")
	printf '%-6s %-36s -> ' "$1" "$2"; curl "${args[@]}" "https://${LAN_HOST}$2" || printf 'no response\n'
}
check GET /display
check GET /display-pair
check GET /login
check GET /
check GET /api/notes
check GET /api/familyhub/ambient/settings
check GET /api/familyhub/ambient/article
check POST /api/auth/login '{}'
check POST /api/familyhub/display/pair '{"code":"1"}'
printf '\nExpected: /display and /display-pair 200; / and /login 302 -> /display; ambient/article 401 (no token);\nother API paths 404;\n'
printf 'pairing POST 400 once the v0.3.1 app is running (404 on older releases).\n'
printf '\nDone. The frame should open https://%s/display. Backups are in %s\n' "$LAN_HOST" "$BACKUP"
